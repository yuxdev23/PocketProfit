/** หา FAQ ที่ keyword ตรงกับข้อความมากที่สุด (โหมด B). คืน null ถ้าไม่เข้าเกณฑ์เลย. */
export function matchFaq(normalized: string): FaqEntry | null {
  let best: { entry: FaqEntry; hits: number } | null = null;
  for (const entry of FAQ) {
    let hits = 0;
    for (const kw of entry.keywords) {
      if (normalized.includes(kw.toLowerCase())) hits += 1;
    }
    if (hits > 0 && (!best || hits > best.hits)) best = { entry, hits };
  }
  return best?.entry ?? null;
}
